#!/usr/bin/env python3
"""Measure every photograph's average brightness and write js/photo-brightness.js.

The footer's lettering shows photographs through the letter "n" on black, so a photograph that is mostly dark
(a night scene, a dark stage) would leave an empty letter. Measuring here, once, means the browser never has
to read pixels itself. Run it after adding or replacing photographs; a test fails if any photograph is missing.

    python3 tools/photo-brightness.py
"""
import json
import subprocess
import sys
from pathlib import Path

from PIL import Image, ImageStat

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "js" / "photo-brightness.js"
HEADER = """/**
 * Generated by tools/photo-brightness.py; do not edit by hand. Each photograph's average brightness, 0 (black)
 * to 1 (white), measured on its smallest file. painted-text.js uses it to leave out pictures too dark to read
 * through the footer's lettering.
 */
(function (root, brightness) {
  if (typeof module === 'object' && module.exports) {
    module.exports = brightness;
  } else {
    root.PORTFOLIO_PHOTO_BRIGHTNESS = brightness;
  }
})(typeof self !== 'undefined' ? self : this, """


def photographs() -> list:
    script = "console.log(JSON.stringify(require('./js/works-photography.js')))"
    return json.loads(subprocess.check_output(["node", "-e", script], cwd=ROOT))


def brightness(path: Path) -> float:
    with Image.open(path) as image:
        return round(ImageStat.Stat(image.convert("L")).mean[0] / 255, 3)


def main() -> int:
    values = {}
    for photo in photographs():
        path = ROOT / "images" / f"{photo['base']}-600.jpg"
        if not path.exists():
            print(f"missing {path}", file=sys.stderr)
            return 1
        values[photo["id"]] = brightness(path)
    body = json.dumps(values, indent=2).replace('"', "'")
    OUTPUT.write_text(f"{HEADER}{body});\n")
    print(f"wrote {len(values)} photographs to {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
